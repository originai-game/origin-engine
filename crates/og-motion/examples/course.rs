//! Chains generations through a course of goals with the intent API on the
//! GPU and writes the motion: world joint positions as JSON for viewing
//! and, with a fourth argument, a glTF animation library of the SOMA
//! skeleton with its feet planted, which a model's `animation { library }`
//! retargets onto its rig at cook time.
//!
//!     cargo run --release -p og-motion --example course -- <bundle> <course.safetensors> <out.json> [out.glb]
//!
//! A course (og-motion-train's `scripts/demo_course.py`) holds one
//! character's four context poses (`context_positions` [4,30,3],
//! `context_rotations` [4,30,3,3]) and its targets in the world
//! (`target_positions` [S,4,30,3], `target_rotations` [S,4,30,3,3],
//! `num_targets` [S]): one goal a step. The motion is the context and every
//! generated frame after it.

use std::time::Instant;

use og_anim::{ChannelPath, ClipAsset, SkeletonAsset};
use og_motion::contract::{JOINTS, Pose};
use og_motion::gpu::Gpu;
use og_motion::intent::{Goal, Motion};
use og_motion::soma::{self, Skeleton};
use og_motion::{Bundle, read_safetensors};

fn poses(positions: &[f32], rotations: &[f32], first: usize, count: usize) -> Vec<Pose> {
    (first..first + count)
        .map(|f| Pose {
            positions: std::array::from_fn(|j| {
                std::array::from_fn(|k| positions[(f * JOINTS + j) * 3 + k])
            }),
            rotations: std::array::from_fn(|j| {
                std::array::from_fn(|a| {
                    std::array::from_fn(|b| rotations[((f * JOINTS + j) * 3 + a) * 3 + b])
                })
            }),
        })
        .collect()
}

/// A glTF binary of `skeleton`'s nodes and `clip` (every channel linear,
/// on one time accessor).
fn glb(skeleton: &SkeletonAsset, clip: &ClipAsset) -> Vec<u8> {
    let mut bin: Vec<u8> = Vec::new();
    let mut views = Vec::new();
    let mut accessors = Vec::new();
    let mut add = |data: &[f32], kind: &str, count: usize, bounds: Option<(f32, f32)>| {
        let offset = bin.len();
        bin.extend(data.iter().flat_map(|v| v.to_le_bytes()));
        views.push(
            serde_json::json!({ "buffer": 0, "byteOffset": offset, "byteLength": data.len() * 4 }),
        );
        let mut a = serde_json::json!({
            "bufferView": views.len() - 1, "componentType": 5126, "count": count, "type": kind,
        });
        if let Some((lo, hi)) = bounds {
            a["min"] = serde_json::json!([lo]);
            a["max"] = serde_json::json!([hi]);
        }
        accessors.push(a);
        accessors.len() - 1
    };
    let times: Vec<f32> = (0..clip.frames)
        .map(|i| (i as f32 / clip.rate).min(clip.duration))
        .collect();
    let time = add(
        &times,
        "SCALAR",
        times.len(),
        Some((0.0, *times.last().unwrap())),
    );
    let mut samplers = Vec::new();
    let mut channels = Vec::new();
    for c in &clip.channels {
        let og_anim::Samples::F32(data) = &c.samples else {
            unreachable!("soma::clip writes every frame")
        };
        let (kind, path) = match c.path {
            ChannelPath::Rotation => ("VEC4", "rotation"),
            _ => ("VEC3", "translation"),
        };
        let output = add(data, kind, clip.frames as usize, None);
        samplers.push(
            serde_json::json!({ "input": time, "output": output, "interpolation": "LINEAR" }),
        );
        channels.push(serde_json::json!({ "sampler": samplers.len() - 1, "target": { "node": c.node, "path": path } }));
    }
    let nodes: Vec<serde_json::Value> = (0..skeleton.nodes.len())
        .map(|i| {
            let n = &skeleton.nodes[i];
            let children: Vec<usize> = (0..skeleton.nodes.len())
                .filter(|&k| skeleton.nodes[k].parent == i as u32)
                .collect();
            let mut v = serde_json::json!({
                "name": n.name,
                "translation": n.rest.translation.to_array(),
                "rotation": n.rest.rotation.to_array(),
            });
            if !children.is_empty() {
                v["children"] = serde_json::json!(children);
            }
            v
        })
        .collect();
    let doc = serde_json::json!({
        "asset": { "version": "2.0", "generator": "og-motion course",
                   "copyright": "Generated by a model licensed by NVIDIA Corporation under the NVIDIA Open Model Agreement." },
        "scene": 0,
        "scenes": [{ "nodes": [0] }],
        "nodes": nodes,
        "animations": [{ "name": clip.name, "samplers": samplers, "channels": channels }],
        "accessors": accessors,
        "bufferViews": views,
        "buffers": [{ "byteLength": bin.len() }],
    });
    let mut json = doc.to_string().into_bytes();
    while !json.len().is_multiple_of(4) {
        json.push(b' ');
    }
    let mut out = Vec::new();
    out.extend(b"glTF");
    out.extend(2u32.to_le_bytes());
    out.extend(((12 + 8 + json.len() + 8 + bin.len()) as u32).to_le_bytes());
    out.extend((json.len() as u32).to_le_bytes());
    out.extend(b"JSON");
    out.extend(json);
    out.extend((bin.len() as u32).to_le_bytes());
    out.extend(b"BIN\0");
    out.extend(bin);
    out
}

fn main() {
    let args: Vec<String> = std::env::args().collect();
    let bundle = Bundle::from_safetensors(&std::fs::read(&args[1]).unwrap()).unwrap();
    let (course, _) = read_safetensors(&std::fs::read(&args[2]).unwrap()).unwrap();
    let t = |name: &str| &course[name].data;
    let mut gpu = pollster::block_on(Gpu::request(&bundle)).unwrap();
    let context: [Pose; 4] = poses(t("context_positions"), t("context_rotations"), 0, 4)
        .try_into()
        .unwrap();
    let mut motion = Motion::default();
    let hero = motion.add(context);
    for (step, k) in t("num_targets").iter().enumerate() {
        let targets = poses(
            t("target_positions"),
            t("target_rotations"),
            step * 4,
            *k as usize,
        );
        motion.push(
            hero,
            Goal {
                targets,
                token_counts: Vec::new(),
                tag: 0,
            },
        );
    }
    let mut frames: Vec<Pose> = context.to_vec();
    let mut contacts: Vec<[f32; 4]> = vec![[1.0; 4]; 4];
    let mut steps = Vec::new();
    let start = Instant::now();
    while motion.goals(hero) > 0 {
        let first = frames.len();
        pollster::block_on(motion.generate_gpu(&mut gpu, usize::MAX)).unwrap();
        while let Some(f) = motion.pop(hero) {
            frames.push(f.pose);
            contacts.push(f.contacts);
        }
        steps.push(serde_json::json!({ "start": first, "frames": frames.len() - first }));
    }
    println!(
        "{} steps, {} frames in {:.0} ms",
        steps.len(),
        frames.len(),
        start.elapsed().as_secs_f64() * 1e3
    );
    let positions: Vec<f32> = frames
        .iter()
        .flat_map(|p| p.positions.iter().flatten().copied())
        .collect();
    let out = serde_json::json!({
        "frames": frames.len(),
        "positions": positions,
        "contacts": contacts.iter().flatten().collect::<Vec<_>>(),
        "steps": steps,
    });
    std::fs::write(&args[3], out.to_string()).unwrap();
    if let Some(path) = args.get(4) {
        let skeleton = Skeleton::from_bundle(&bundle).unwrap();
        let asset = skeleton.asset();
        let mut local: Vec<_> = frames.iter().map(|p| skeleton.local(p)).collect();
        soma::plant_feet(&asset, &mut local, &contacts);
        let clip = soma::clip("course", &asset, &local);
        std::fs::write(path, glb(&asset, &clip)).unwrap();
        println!(
            "{path}: {} frames of the SOMA skeleton, feet planted",
            clip.frames
        );
    }
}
