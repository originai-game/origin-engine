// Writes crates/og-i18n/src/cldr.rs: the CLDR subset og.i18n's formatting
// reads (compact numbers, currencies, dates, times), for the languages
// og-i18n's plural rules already cover, plus zh-Hant.
//
//   mkdir /tmp/cldr && cd /tmp/cldr
//   npm pack cldr-numbers-full@49.0.0 cldr-dates-full@49.0.0 cldr-core@49.0.0
//   for f in *.tgz; do mkdir -p "${f%.tgz}" && tar xzf "$f" -C "${f%.tgz}"; done
//   bun crates/og-i18n/scripts/cldr.ts /tmp/cldr
//
// The output is committed; rerun only to move to a newer CLDR.

import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const VERSION = "49.0.0";
const root = process.argv[2];
if (!root) throw new Error("usage: bun crates/og-i18n/scripts/cldr.ts <dir with the unpacked cldr-json packages>");
const pkg = (name: string) => join(root, `${name}-${VERSION}`, "package");
const json = (path: string) => JSON.parse(readFileSync(path, "utf8"));

/** og-i18n's plural languages (plural.rs), each its CLDR default locale, and zh-Hant. */
const LOCALES = [
  "am", "ar", "be", "bg", "bn", "ca", "cs", "da", "de", "el", "en", "es", "et", "eu", "fa", "fi", "fr",
  "gl", "gu", "he", "hi", "hu", "id", "it", "ja", "km", "kn", "ko", "lo", "mr", "ms", "my", "nb", "nl",
  "pl", "pt", "ru", "sk", "sv", "th", "tr", "uk", "vi", "zh", "zh-Hant", "zu",
];

/** The currencies whose symbols the subset carries (others print their code). */
const CURRENCIES = [
  "USD", "EUR", "GBP", "JPY", "CNY", "KRW", "INR", "BRL", "RUB", "TRY", "CAD", "AUD", "MXN", "CHF",
  "SEK", "NOK", "DKK", "PLN", "CZK", "HUF", "IDR", "THB", "VND", "PHP", "MYR", "SGD", "HKD", "TWD",
  "ZAR", "SAR", "AED", "ILS", "UAH", "EGP", "NGN", "ARS", "CLP", "COP", "NZD", "BGN",
];

const rs = (s: string) =>
  '"' + [...s].map((c) => (c === "\\" ? "\\\\" : c === '"' ? '\\"' : c.charCodeAt(0) < 32 ? `\\u{${c.charCodeAt(0).toString(16)}}` : c)).join("") + '"';

/** A CLDR pattern's literal text without its quoting ('' is a quote). */
const unquote = (s: string) => s.replace(/'([^']*)'/g, (_, t: string) => (t === "" ? "'" : t));

/** A compact pattern ("0 Mio'.'", "00K", "0") as (zeros, prefix, suffix); zeros 0: not compacted. */
function compact(p: string | undefined): [number, string, string] {
  if (!p || p === "0") return [0, "", ""];
  const m = /^(.*?)(0+)(.*)$/.exec(p);
  if (!m) return [0, "", ""];
  return [m[2]!.length, unquote(m[1]!), unquote(m[3]!)];
}

/** The primary and secondary group sizes of a decimal pattern ("#,##,##0.###": 3, 2). */
function grouping(p: string): [number, number] {
  const int = p.split(";")[0]!.split(".")[0]!;
  const parts = int.split(",");
  if (parts.length < 2) return [0, 0];
  const primary = parts[parts.length - 1]!.length;
  const secondary = parts.length > 2 ? parts[parts.length - 2]!.length : primary;
  return [primary, secondary];
}

const fractions = json(join(pkg("cldr-core"), "supplemental/currencyData.json")).supplemental.currencyData.fractions;
const systems = json(join(pkg("cldr-core"), "supplemental/numberingSystems.json")).supplemental.numberingSystems;
const symbolsOf = (l: string) => json(join(pkg("cldr-numbers-full"), "main", l, "currencies.json")).main[l].numbers.currencies;
const en = symbolsOf("en");

const out: string[] = [];
out.push(`//! Generated by \`bun crates/og-i18n/scripts/cldr.ts\` from CLDR ${VERSION} (the cldr-json`);
out.push(`//! packages cldr-numbers-full, cldr-dates-full and cldr-core). Do not edit:`);
out.push(`//! rerun the script.`);
out.push(``);
out.push(`use crate::format::{Currency, LocaleData};`);
out.push(``);
out.push(`/// Each currency's code, its symbol in en and its fraction digits.`);
out.push(`pub(crate) static CURRENCIES: &[Currency] = &[`);
for (const c of CURRENCIES) {
  const digits = Number((fractions[c] ?? fractions.DEFAULT)._digits);
  out.push(`    Currency { code: ${rs(c)}, symbol: ${rs(en[c]?.symbol ?? c)}, digits: ${digits} },`);
}
out.push(`];`);
out.push(``);
out.push(`/// The locales, sorted by tag.`);
out.push(`pub(crate) static LOCALES: &[LocaleData] = &[`);
for (const l of [...LOCALES].sort()) {
  const n = json(join(pkg("cldr-numbers-full"), "main", l, "numbers.json")).main[l].numbers;
  const ns: string = n.defaultNumberingSystem;
  const sym = n[`symbols-numberSystem-${ns}`] ?? n["symbols-numberSystem-latn"];
  const dec = n[`decimalFormats-numberSystem-${ns}`] ?? n["decimalFormats-numberSystem-latn"];
  const cur = n[`currencyFormats-numberSystem-${ns}`] ?? n["currencyFormats-numberSystem-latn"];
  const short = dec.short.decimalFormat;
  const compacts = Array.from({ length: 12 }, (_, k) => compact(short[`1${"0".repeat(k + 3)}-count-other`]));
  const own = symbolsOf(l);
  const symbols = CURRENCIES.filter((c) => own[c]?.symbol && own[c].symbol !== (en[c]?.symbol ?? c)).map((c) => `(${rs(c)}, ${rs(own[c].symbol)})`);
  const g = json(join(pkg("cldr-dates-full"), "main", l, "ca-gregorian.json")).main[l].dates.calendars.gregorian;
  const months = (w: string) => Array.from({ length: 12 }, (_, k) => rs(g.months.format[w][`${k + 1}`])).join(", ");
  const days = (w: string) => ["sun", "mon", "tue", "wed", "thu", "fri", "sat"].map((d) => rs(g.days.format[w][d])).join(", ");
  const periods = g.dayPeriods.format.abbreviated;
  const [primary, secondary] = grouping(dec.standard);
  const digits = ns === "latn" ? "None" : `Some(${rs(systems[ns]._digits)})`;
  out.push(`    LocaleData {`);
  out.push(`        tag: ${rs(l)},`);
  out.push(`        digits: ${digits},`);
  out.push(`        decimal: ${rs(sym.decimal)},`);
  out.push(`        group: ${rs(sym.group)},`);
  out.push(`        minus: ${rs(sym.minusSign)},`);
  out.push(`        time_separator: ${rs(sym.timeSeparator)},`);
  out.push(`        grouping: (${primary}, ${secondary}),`);
  out.push(`        min_grouping: ${Number(n.minimumGroupingDigits)},`);
  out.push(`        compact: [${compacts.map(([z, p, s]) => `(${z}, ${rs(p)}, ${rs(s)})`).join(", ")}],`);
  out.push(`        currency: ${rs(cur.standard.split(";")[0])},`);
  out.push(`        symbols: &[${symbols.join(", ")}],`);
  out.push(`        months: [${months("wide")}],`);
  out.push(`        months_short: [${months("abbreviated")}],`);
  out.push(`        days: [${days("wide")}],`);
  out.push(`        days_short: [${days("abbreviated")}],`);
  out.push(`        am: ${rs(periods.am)},`);
  out.push(`        pm: ${rs(periods.pm)},`);
  out.push(`        date: [${["full", "long", "medium", "short"].map((s) => rs(g.dateFormats[s])).join(", ")}],`);
  out.push(`        time: [${["medium", "short"].map((s) => rs(g.timeFormats[s])).join(", ")}],`);
  out.push(`    },`);
}
out.push(`];`);
writeFileSync(join(import.meta.dir, "../src/cldr.rs"), out.join("\n") + "\n");
