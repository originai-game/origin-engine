//! Origin Engine core: the vocabulary every other crate shares.
//!
//! | module | what it owns |
//! |---|---|
//! | [`error`] | [`Error`] (kind + reason) and [`Result`]: errors are values |
//! | [`handle`] | generational handles: [`RawHandle`], [`HandleAllocator`], [`Handle`], [`Pool`] |
//! | [`reflect`] | [`Reflect`] and `#[derive(Reflect)]`, [`Schema`] and its JSON, packed [`Layout`]s |
//! | [`ogt`] | the `.ogt` text format: [`ogt::Document`] reader and canonical writer |
//! | [`rng`] | [`Rng`], the deterministic generator shared with the platform scaffolds |
//! | [`math`] | glam re-exported, plus deterministic `sin`/`cos`/`atan2`/`exp`/`ln`/`pow`, and [`math::world_pose`] down a parent chain |
//! | [`time`] | [`Time`], the fixed-tick clock |
//! | [`hash`] | [`hash::StableHasher`], the stable 64-bit hash for world and layout hashes |
//!
//! Invariants: no global mutable state; every fallible call returns
//! `Result<_, Error>`; nothing here reads the wall clock or the host's
//! floating-point library; byte layouts are little-endian.

#[cfg(target_endian = "big")]
compile_error!(
    "Origin Engine stores packed layouts and snapshots little-endian; big-endian hosts are not supported"
);

