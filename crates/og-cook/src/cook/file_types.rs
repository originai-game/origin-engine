//! File reference from the actual cook registry and parser line tables.
use super::{kinds, systems::terrain_schema};
use crate::grammar::Line;
use std::fmt::Write;

pub const PATH: &str = "crates/og-api/guides/file-types.md";

fn table(out: &mut String, fields: &[Line]) {
    out.push_str("| Field | Default | Meaning |\n|---|---|---|\n");
    for f in fields {
        let _ = writeln!(
            out,
            "| `{} {}` | `{}` | {} |",
            f.key,
            f.args.replace('|', "\\|"),
            f.default,
            f.doc
        );
    }
}

pub fn markdown() -> Result<String, String> {
    terrain_schema::check_defaults()?;
    let mut out = String::from(
        "<!-- Generated by og api gen from the cook registry and parser line tables. -->\n# File types\n\nUse `og api list --kind file`, `og api show file:terrain` or `og api find erosion --kind file`. An asset starts with `type <name>`, `version <integer>`, `---`. Input paths and field coverage below are per type, not runtime API fields.\n\n## 1. Cook assets\n\n",
    );
    let mut types: Vec<_> = kinds::kinds()
        .flat_map(|k| k.types.iter().map(move |t| (*t, k.name)))
        .collect();
    types.sort();
    for (ty, owner) in types {
        let _ = writeln!(
            out,
            "<a id=\"file-{ty}\"></a>\n### `file:{ty}`\n\nAn authored `{ty}` asset, cooked by `{owner}`. Input: `.ogt` under assets/.\n"
        );
        match ty {
            "terrain" => {
                out.push_str("Field coverage: parser line tables, including every nested block below. Output: tiled terrain, control pages and collision data, loaded with og.terrain.load.\n\n");
                for (path, fields) in terrain_schema::BLOCKS {
                    if !path.is_empty() {
                        let _ = writeln!(out, "<a id=\"file-terrain-{path}\"></a>\n### `file:terrain.{path}`\n\nTerrain `{path}` block fields.\n");
                    }
                    table(&mut out, fields);
                    out.push('\n');
                }
            }
            "particles" | "effect" | "vfx" => {
                out.push_str("Field coverage: parser line tables; see `effect-files` for nested blocks and constraints.\n\n");
                table(&mut out, match ty { "particles" => crate::fx::EMITTER_LINES, "effect" => crate::effect::EFFECT_LINES, _ => crate::vfx::VFX_LINES });
            }
            _ => out.push_str("Field coverage: not yet migrated to parser line tables. The type is registered and cookable; use its loading/authoring guide for current syntax, not runtime record fields.\n"),
        }
        out.push('\n');
    }
    out.push_str("## 2. Other engineering sources\n\n");
    for (ty, doc) in [
        (
            "project",
            "project.ogt: project configuration, not an asset. See start and conventions.",
        ),
        (
            "import",
            "A source's .ogt sidecar or directory import.ogt: input settings, not an independent asset. See loading.",
        ),
        (
            "model-program",
            ".shape.json: model program operations; consumed by model. See model.",
        ),
        (
            "theme",
            "theme.json: compiles to pack.json and UI art. See themes and theme-tokens.",
        ),
        ("pack", "pack.json: UI style pack. See themes."),
        (
            "font-extension",
            "extension.json of kind font, with TTF/OTF sources. See localization.",
        ),
        (
            "tsx",
            "TSX is the UI source; TS/TSX bundling is not a cook generator. See ui-tsx.",
        ),
        (
            "animgraph",
            "Runtime anim.graph text only: not currently a registered cook type. See animation.",
        ),
        (
            "probe-record",
            "cooked/probes/<key>.ogt: derived bake record, not an authored input. See render.",
        ),
    ] {
        let _ = writeln!(out, "<a id=\"file-{ty}\"></a>\n### `file:{ty}`\n\n{doc}\n");
    }
    out.push_str("Removed style.ogt and .svelte are rejected, not compatibility formats. For native source extensions, use the loading guide; a decoder supported as a parent asset's input is not necessarily an independent cook type.\n");
    Ok(out)
}
