//! File reference from the actual cook registry and parser line tables.
use super::kinds;
use crate::grammar::Line;
use std::collections::BTreeSet;
use std::fmt::Write;

pub const PATH: &str = "crates/og-api/guides/file-types.md";

fn table(out: &mut String, fields: &[Line]) {
    out.push_str("| Field | Default | Meaning |\n|---|---|---|\n");
    for f in fields {
        let _ = writeln!(
            out,
            "| `{} {}` | `{}` | {} |",
            f.key,
            f.args.replace('|', "\\|"),
            f.default,
            f.doc.replace('|', "\\|").replace('\n', " ")
        );
    }
}

fn block(out: &mut String, name: &str, fields: &[Line]) {
    let anchor = name.replace('.', "-");
    let _ = writeln!(out, "\n<a id=\"file-{anchor}\"></a>\n### `file:{name}`\n");
    table(out, fields);
}

