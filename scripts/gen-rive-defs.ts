// Rive's pinned generated headers -> the importer's Rust type/property tables.
//   bun scripts/gen-rive-defs.ts /path/to/rive-runtime
import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const root = resolve(process.argv[2]!);
const revResult = Bun.spawnSync(["git", "-C", root, "rev-parse", "HEAD"]);
if (revResult.exitCode) throw new Error(revResult.stderr.toString());
const rev = revResult.stdout.toString().trim();
const out = resolve(import.meta.dir, "../crates/og-cook/src/cook/riv/defs.rs");
const classes = new Map<string, { key?: number; parent: string; props: [string, number, string][] }>();
function defaultValue(type: string, value: string): string {
  let v = value.replace(/[fu]+$/, "");
  if (v === "true" || v === "false") return v === "true" ? "1.0" : "0.0";
  // Number() differs from Python int(s, 0) for signed hexadecimal literals.
  const sign = v.startsWith("-") ? -1 : 1;
  let n = /^[+-]?0[xob]/i.test(v) ? sign * Number(v.replace(/^[+-]/, "")) : Number(v);
  if (!Number.isFinite(n)) return "0.0";
  if (type === "uint32_t" && Number.isInteger(n) && n < 0) n >>>= 0;
  if (Number.isInteger(n)) return `${n}.0`;
  return String(n);
}
for (const path of [...new Bun.Glob("**/*_base.hpp").scanSync(join(root, "include/rive/generated"))].sort()) {
  const text = readFileSync(join(root, "include/rive/generated", path), "utf8");
  const m = /class (\w+)Base\s*:\s*public\s+(\w+)/.exec(text);
  if (!m) continue;
  const inits = new Map<string, [string, string]>();
  for (const [, type, member, val] of text.matchAll(/^\s+([\w:<>]+) m_(\w+) = ([^;]+);/gm)) {
    const name = member![0]!.toLowerCase() + member!.slice(1);
    if (!inits.has(name)) inits.set(name, [type!, val!.trim()]);
  }
  const tk = /static const uint16_t typeKey = (\d+);/.exec(text);
  const props: [string, number, string][] = [...text.matchAll(/static const uint16_t (\w+)PropertyKey = (\d+);/g)].map(([, p, k]) => [
    p!,
    Number(k),
    defaultValue(...(inits.get(p!) ?? ["", "0"])),
  ]);
  classes.set(m[1]!, { key: tk ? Number(tk[1]) : undefined, parent: m[2]!.replace(/Base$/, ""), props });
}
const registry = readFileSync(join(root, "include/rive/generated/core_registry.hpp"), "utf8");
let body = registry.slice(registry.indexOf("static int propertyFieldId(int propertyKey)"));
body = body.slice(0, body.indexOf("\n  }\n"));
const field = new Map<string, string>();
let pending: string[] = [];
for (const line of body.split("\n")) {
  const c = /case (\w+)Base::(\w+)PropertyKey:/.exec(line);
  if (c) {
    pending.push(`${c[1]}/${c[2]}`);
    continue;
  }
  const r = /return Core(\w+)Type::id;/.exec(line);
  if (r) {
    for (const p of pending) field.set(p, r[1]!);
    pending = [];
  }
}
let make = registry.slice(registry.indexOf("static Core* makeCoreInstance(int typeKey)"));
make = make.slice(0, make.indexOf("\n  }\n"));
const concrete = new Set([...make.matchAll(/case (\w+)Base::typeKey:/g)].map((m) => m[1]!));
const kinds: Record<string, string> = {
  Uint: "Uint",
  Id: "Uint",
  Int: "Int",
  Bool: "Bool",
  Double: "Float",
  Color: "Color",
  String: "String",
  Bytes: "Bytes",
};
const types: string[] = [],
  props: [number, string][] = [];
for (const [name, cls] of [...classes].sort(
  ([an, a], [bn, b]) => Number(a.key == null) - Number(b.key == null) || (a.key ?? 0) - (b.key ?? 0) || (an < bn ? -1 : an > bn ? 1 : 0),
)) {
  if (cls.key != null) {
    const p = classes.get(cls.parent)?.key;
    types.push(`    (${cls.key}, "${name}", ${p == null ? "None" : `Some(${p})`}, ${concrete.has(name)}),`);
  }
  for (const [p, k, d] of cls.props) {
    const f = field.get(`${name}/${p}`);
    if (f) props.push([k, `    (${k}, "${name}", "${p}", Field::${kinds[f]}, ${d}),`]);
  }
}
writeFileSync(
  out,
  `//! Generated by scripts/gen-rive-defs.ts from rive-runtime ${rev}
//! (MIT, third_party/rive/): the .riv format's type keys, each with its
//! parent's, and its property keys with their field types. Do not edit.

use super::Field;

/// (type key, name, parent type key, whether the runtime makes it).
pub(crate) const TYPES: &[(u16, &str, Option<u16>, bool)] = &[
${types.join("\n")}
];

/// (property key, owning type, property, field type, default: the value a
/// file that leaves it out has; a colour's 0xAARRGGBB, 0 for text).
pub(crate) const PROPERTIES: &[(u16, &str, &str, Field, f64)] = &[
${props
  .sort(([a, x], [b, y]) => a - b || (x < y ? -1 : x > y ? 1 : 0))
  .map(([, s]) => s)
  .join("\n")}
];
`,
);
console.log(`${out}: ${types.length} types, ${props.length} properties from ${rev}`);
