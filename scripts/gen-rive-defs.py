#!/usr/bin/env python3
"""Writes crates/og-cook/src/cook/riv/defs.rs: the .riv format's type keys
and property keys (with their field types) from rive-runtime's generated
headers (MIT, third_party/rive/).

    scripts/gen-rive-defs.py /path/to/rive-runtime   # at the pinned revision

The revision is the one third_party/rive/README.md names; a new one is a
deliberate update of the importer, not a refresh.
"""
import pathlib
import re
import subprocess
import sys

root = pathlib.Path(sys.argv[1])
out = pathlib.Path(__file__).resolve().parent.parent / "crates/og-cook/src/cook/riv/defs.rs"
rev = subprocess.check_output(["git", "-C", str(root), "rev-parse", "HEAD"], text=True).strip()

classes = {}  # name -> (type key or None, parent name or None, [(prop, key, default)])


def default(ty, val):
    """A member initialiser as a Rust f64 literal (strings and bytes: 0)."""
    v = val.rstrip("fu")
    if v in ("true", "false"):
        return "1.0" if v == "true" else "0.0"
    try:
        n = int(v, 0)
        if ty in ("uint32_t", "int") and n < 0 and ty == "uint32_t":
            n &= 0xFFFFFFFF
        return f"{float(n)!r}"
    except ValueError:
        pass
    try:
        return f"{float(v)!r}"
    except ValueError:
        return "0.0"
for h in sorted((root / "include/rive/generated").rglob("*_base.hpp")):
    text = h.read_text()
    m = re.search(r"class (\w+)Base\s*:\s*public\s+(\w+)", text)
    if not m:
        continue
    name, parent = m.group(1), m.group(2)
    parent = parent[:-4] if parent.endswith("Base") else parent
    tk = re.search(r"static const uint16_t typeKey = (\d+);", text)
    keys = re.findall(r"static const uint16_t (\w+)PropertyKey = (\d+);", text)
    # The defaults a file leaves out: the members' initialisers.
    inits = {}
    for ty, member, val in re.findall(r"^\s+([\w:<>]+) m_(\w+) = ([^;]+);", text, re.M):
        inits.setdefault(member[0].lower() + member[1:], (ty, val.strip()))
    props = [(p, int(k), default(*inits.get(p, ("", "0")))) for p, k in keys]
    classes[name] = (int(tk.group(1)) if tk else None, parent, props)

registry = (root / "include/rive/generated/core_registry.hpp").read_text()
body = registry[registry.index("static int propertyFieldId(int propertyKey)"):]
body = body[: body.index("\n  }\n")]
field = {}
pending = []
for line in body.splitlines():
    c = re.search(r"case (\w+)Base::(\w+)PropertyKey:", line)
    if c:
        pending.append((c.group(1), c.group(2)))
        continue
    r = re.search(r"return Core(\w+)Type::id;", line)
    if r:
        for cls, prop in pending:
            field[(cls, prop)] = r.group(1)
        pending = []

# The types the runtime makes (others read as an empty object that still
# takes an artboard slot, File::readObjects' readNullObject).
make = registry[registry.index("static Core* makeCoreInstance(int typeKey)"):]
make = make[: make.index("\n  }\n")]
concrete = set(re.findall(r"case (\w+)Base::typeKey:", make))

kinds = {"Uint": "Uint", "Id": "Uint", "Int": "Int", "Bool": "Bool", "Double": "Float",
         "Color": "Color", "String": "String", "Bytes": "Bytes"}
types, props = [], []
for name, (tk, parent, ps) in sorted(classes.items(), key=lambda kv: (kv[1][0] is None, kv[1][0] or 0, kv[0])):
    if tk is not None:
        ptk = classes.get(parent, (None,))[0]
        types.append(f'    ({tk}, "{name}", {"None" if ptk is None else f"Some({ptk})"}, {"true" if name in concrete else "false"}),')
    for p, k, d in ps:
        f = field.get((name, p))
        if f is None:
            continue
        props.append((k, f'    ({k}, "{name}", "{p}", Field::{kinds[f]}, {d}),'))

out.write_text(f"""//! Generated by scripts/gen-rive-defs.py from rive-runtime {rev}
//! (MIT, third_party/rive/): the .riv format's type keys, each with its
//! parent's, and its property keys with their field types. Do not edit.

use super::Field;

/// (type key, name, parent type key, whether the runtime makes it).
pub(crate) const TYPES: &[(u16, &str, Option<u16>, bool)] = &[
{chr(10).join(types)}
];

/// (property key, owning type, property, field type, default: the value a
/// file that leaves it out has; a colour's 0xAARRGGBB, 0 for text).
pub(crate) const PROPERTIES: &[(u16, &str, &str, Field, f64)] = &[
{chr(10).join(l for _, l in sorted(props))}
];
""")
print(f"{out}: {len(types)} types, {len(props)} properties from {rev}")
