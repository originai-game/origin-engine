// Import once from iconoir v7.12.1; regenerate/check from the vendored SVGs thereafter.
// bun scripts/fallback-icons.ts [--source path/to/iconoir/icons/regular] [--check]
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";

const root = resolve(import.meta.dir, "..");
const kit = "packages/engine/extensions/development-fallback-icons";
const groups = {
  settings: "settings language gamepad sound-high sound-off eye eye-closed accessibility text-size palette",
  navigation: "back:nav-arrow-left forward:nav-arrow-right up:nav-arrow-up down:nav-arrow-down home menu view-grid search refresh undo",
  currencies: "coin:coins gem:hexagon dollar euro yen pound wallet cart shopping-bag percentage",
  stats: "heart shield flash trophy medal crown timer hourglass stats-up-square stats-down-square",
  items: "bag key gift potion flask cube hammer apple leaf package",
  skills: "magic-wand sparks fire:fire-flame snow-flake droplet sun:sun-light moon:half-moon magnet-energy target:archery-match archery",
  social: "user group chat-bubble share:share-android bell leaderboard-star healthcare peace-hand megaphone community",
  media: "play pause music:music-double-note microphone camera video-camera skip-next skip-prev fast-arrow-right fast-arrow-left",
  system: "check close:xmark plus minus info:info-circle warning:warning-triangle help:help-circle lock floppy-disk trash",
  world: "map map-pin compass globe clock rocket flag:triangle-flag puzzle dice-five planet",
};
const selected = Object.entries(groups).flatMap(([group, names]) => names.split(" ").map(pair => {
  const [name, source = name] = pair.split(":");
  if (!name || !source) throw new Error(`Invalid icon ${pair}`);
  return { name, source, group, path: `ui-kits/development-fallback-icons/vectors/${group}/${name}.ogt` };
}));
if (selected.length !== 100 || new Set(selected.map(i => i.name)).size !== 100) throw new Error("Expected 100 unique names");
const sourceArg = process.argv.indexOf("--source");
const source = sourceArg < 0 ? undefined : process.argv[sourceArg + 1];
const check = process.argv.includes("--check");
if (check && source) throw new Error("--check never imports files");
function output(path: string, text: string): void {
  const file = join(root, path);
  if (check) {
    if (!existsSync(file) || readFileSync(file, "utf8") !== text) throw new Error(`${path} differs; run bun scripts/fallback-icons.ts`);
  } else {
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, text);
  }
}
for (const icon of selected) {
  const vendor = join(root, "third_party/iconoir/icons", `${icon.source}.svg`);
  if (source) {
    mkdirSync(dirname(vendor), { recursive: true });
    copyFileSync(join(source, `${icon.source}.svg`), vendor);
  }
  const svg = readFileSync(vendor, "utf8").trim();
  output(`${kit}/vectors/${icon.group}/${icon.name}.ogt`, `type vector\nversion 1\n---\n# Development fallback. Replace before publishing. Iconoir 7.12.1, MIT; see LICENSE.\nsvg ${JSON.stringify(svg)}\ntolerance 0.1\n`);
}
output(`${kit}/icons.json`, JSON.stringify({ format: 1, developmentFallback: true, license: "MIT", upstream: "iconoir@7.12.1", icons: selected }, null, 2) + "\n");
output(`${kit}/icons.ts`, `// Generated by scripts/fallback-icons.ts. Development assets, not finished game art.\nimport type { IconAtlasDesc } from "@origingame/engine";\n\nexport const fallbackIcons: IconAtlasDesc = {\n  vectors: ${JSON.stringify(selected.map(({ name, path }) => ({ name, path })), null, 2)}\n};\n`);
const license = readFileSync(join(root, "third_party/iconoir/LICENSE"), "utf8");
output(`${kit}/LICENSE`, license);
process.stdout.write(`${check ? "Checked" : "Generated"} ${selected.length} development fallback vectors\n`);
