// Writes og-text's OpenType -> BCP 47 table from the pinned harfrust source.
//   bun scripts/gen-ot-languages.ts [path/to/harfrust/src/hb/tag_table.rs]
import { readFileSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { join, resolve } from "node:path";

const root = resolve(import.meta.dir, "..");
const version = /name = "harfrust"\nversion = "([^"]+)"/.exec(readFileSync(join(root, "Cargo.lock"), "utf8"))![1]!;
const source =
  process.argv[2] ??
  [...new Bun.Glob(`*/harfrust-${version}/src/hb/tag_table.rs`).scanSync(join(homedir(), ".cargo/registry/src"))].map((p) =>
    join(homedir(), ".cargo/registry/src", p),
  )[0]!;
let table = readFileSync(source, "utf8");
table = table.slice(table.indexOf("OPEN_TYPE_LANGUAGES"));
table = table.slice(0, table.indexOf("];"));
const first = new Map<string, string>(),
  back = new Map<string, string>();
for (const [, lang, tag] of table.matchAll(/lang\(b"([^"]+)"\),\s*tag:\s*Tag::new\(b"(....)"\)/g))
  if (!first.has(lang!)) first.set(lang!, tag!);
for (const [lang, tag] of first) {
  const prior = back.get(tag);
  if (!prior || lang.length < prior.length || (lang.length === prior.length && lang < prior)) back.set(tag, lang);
}
const rows = [...back]
  .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
  .map(([tag, lang]) => `    (*b"${tag}", "${lang}"),`)
  .join("\n");
writeFileSync(
  join(root, "crates/og-text/src/ot_languages.rs"),
  `// Generated by scripts/gen-ot-languages.ts from harfrust ${version}'s
// src/hb/tag_table.rs (HarfBuzz's language table, MIT: see
// third_party/harfrust/LICENSE). Do not edit.

/// Each OpenType language system tag and the BCP 47 language that shapes in
/// it first, sorted by tag.
pub(crate) static OT_LANGUAGES: &[([u8; 4], &str)] = &[
${rows}
];
`,
);
console.log(`${back.size} tags`);
