#!/usr/bin/env python3
"""Writes crates/og-text/src/ot_languages.rs: each OpenType language system
tag and the BCP 47 language whose first tag it is, from harfrust's copy of
HarfBuzz's table (third_party/harfrust/LICENSE). Run after a harfrust bump:

    python3 scripts/gen-ot-languages.py [path/to/harfrust/src/hb/tag_table.rs]
"""

import glob
import os
import re
import sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
lock = open(os.path.join(root, "Cargo.lock")).read()
version = re.search(r'name = "harfrust"\nversion = "([^"]+)"', lock).group(1)
src = sys.argv[1] if len(sys.argv) > 1 else glob.glob(
    os.path.expanduser(f"~/.cargo/registry/src/*/harfrust-{version}/src/hb/tag_table.rs")
)[0]
table = open(src).read()
table = table[table.index("OPEN_TYPE_LANGUAGES") :]
table = table[: table.index("];")]
entries = re.findall(r'lang\(b"([^"]+)"\),\s*tag:\s*Tag::new\(b"(....)"\)', table)

# A language's first tag is the one HarfBuzz shapes it with, so a tag maps
# back to a language that round-trips to it: the shortest, then first in
# alphabetical order.
first = {}
for lang, tag in entries:
    first.setdefault(lang, tag)
back = {}
for lang, tag in first.items():
    if tag not in back or (len(lang), lang) < (len(back[tag]), back[tag]):
        back[tag] = lang

rows = "\n".join(
    f'    (*b"{tag}", "{lang}"),' for tag, lang in sorted(back.items())
)
out = f"""// Generated by scripts/gen-ot-languages.py from harfrust {version}'s
// src/hb/tag_table.rs (HarfBuzz's language table, MIT: see
// third_party/harfrust/LICENSE). Do not edit.

/// Each OpenType language system tag and the BCP 47 language that shapes in
/// it first, sorted by tag.
pub(crate) static OT_LANGUAGES: &[([u8; 4], &str)] = &[
{rows}
];
"""
open(os.path.join(root, "crates/og-text/src/ot_languages.rs"), "w").write(out)
print(f"{len(back)} tags")
